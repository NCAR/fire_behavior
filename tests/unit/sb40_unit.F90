program sb40_unit
  ! Native fuel tables, category preservation, curing and component ROS checks.
  ! Synthetic map tiles include every burnable model and each accepted no-fuel
  ! code. Scientific checks use dry-mass moisture fractions and zero-wind ROS;
  ! failures identify lost fuel mass, live components or unsafe category mapping.
  use, intrinsic :: ieee_arithmetic, only : ieee_value, ieee_quiet_nan, ieee_is_finite
  use, intrinsic :: iso_fortran_env, only : REAL64
  use fuel_scott_burgan_mod, only : fuel_scott_burgan_t
  use fuel_anderson_mod, only : fuel_anderson_t
  use constants_mod, only : CONVERT_TON_PER_ACRE_TO_KG_PER_M_SQ
  use ros_sb40_mod, only : Calc_sb40_parameters
  use ros_wrffire_mod, only : ros_wrffire_t
  use fmc_wrffire_mod, only : fmc_wrffire_t
  use fire_physics_mod, only : Calc_fire_fluxes
  use state_mod, only : state_fire_t
#ifdef DM_PARALLEL
  use mpi
#endif
  implicit none
  type(fuel_scott_burgan_t) :: fuels
  type(fuel_anderson_t) :: anderson
  type(ros_wrffire_t) :: ros
  type(fmc_wrffire_t) :: fmc
  integer :: codes(46), indices(0:47,0:3), i, k, n, comm, rank, ierr, provided
  integer :: i_start(4)=[1,24,1,24], i_end(4)=[23,46,23,46]
  integer :: j_start(4)=[1,1,2,2], j_end(4)=[1,1,2,2]
  real :: external(0:47,0:3), original(0:47,0:3), aggregate(0:47,0:3)
  real :: mc(6), loads(6), total, beta, b, wind, r0, iboros, dead, live, mx, baseline
  character(len=32) :: scenario
  comm = 0
  rank = 0
#ifdef DM_PARALLEL
  call MPI_Init_thread(MPI_THREAD_FUNNELED,provided,ierr)
  if (provided < MPI_THREAD_FUNNELED) error stop 'MPI thread support is insufficient'
  comm = MPI_COMM_WORLD
  call MPI_Comm_rank(comm,rank,ierr)
#endif
  call get_command_argument(1,scenario)
  call fuels%Initialization(1.0)
  call anderson%Initialization(1.0)
  codes = [(i,i=101,109),(i,i=121,124),(i,i=141,149),(i,i=161,165), &
      (i,i=181,189),(i,i=201,204),14,91,92,93,98,99]
  external = -9999.0
  external(1:46,1) = real(codes)
  external(1:46,2) = real(codes)
  ! Invalid categories must fail before table access. Only rank zero is changed
  ! so an MPI launch also tests collective rejection of a rank-local defect.
  if (rank == 0) then
    select case(trim(scenario))
    case('unknown')
      external(1,1) = 205.0
    case('reserved_nb')
      external(1,1) = 94.0
    case('fractional')
      external(1,1) = 101.5
    case('missing')
      external(1,1) = -9999.0
    case('nonfinite')
      external(1,1) = ieee_value(0.0,ieee_quiet_nan)
    end select
  end if
  original = external
  call fuels%Resolve_fuel_indices(0,47,0,3,4,i_start,i_end,j_start,j_end,external,indices,comm)
  if (trim(scenario) /= 'valid' .and. trim(scenario) /= 'reference') error stop 'invalid map was accepted'
  if (any(external /= original)) error stop 'external categories were overwritten'
  do i = 1, 40
    if (any(indices(i,1:2) /= i)) error stop 'burnable mapping differs'
    if (len_trim(fuels%fuel_name(i)) == 0) error stop 'missing fuel name'
  end do
  ! Independent zero-wind values generated by compiled USFS firelab/behave,
  ! commit f3b2943e69abca942e795c5b1b45276f6338abb5. Inputs are fractional
  ! dry-mass moisture and outputs are ft/min and BTU/ft2/min. Fully cured and
  ! >120% herbaceous cases avoid Behave's rounded intermediate curing formula.
  ! GS1 and SH5 retain woody reaction; TL8 and SB4 exercise coarse dead fuel.
  mc = [0.06,0.07,0.08,0.08,0.30,0.90]
  call Reference(101,mc,0.992298189023,394.682359940,0.0)
  call Reference(106,mc,6.63981331787,5907.95663767,0.0)
  call Reference(121,mc,0.909441715777,721.280259219,662.860065340)
  call Reference(145,mc,2.38868360093,2767.19086113,2374.93331633)
  call Reference(188,mc,0.829132340548,3251.24921467,0.0)
  call Reference(204,mc,4.08154343226,7148.17046654,0.0)
  mc(5) = 1.21
  call Reference(106,mc,0.0385475773946,168.798761076,0.0)
  call Reference(163,mc,1.00808106206,1407.73448365,1818.99820013)
  if (any(indices(41:46,1:2) /= 41)) error stop 'NB codes did not share row 41'
  if (any(indices(:,0) /= 0)) error stop 'unavailable halos silently marked burnable or nonburnable'
  if (size(fuels%waf) /= 41 .or. size(anderson%waf) /= 14) error stop 'missing no-fuel WAF row'
  if (fuels%Resolve_fuel_index(15) /= 0 .or. fuels%Resolve_fuel_index(54) /= 0) error stop 'legacy rows accepted'
  do i = 94, 97
    if (fuels%Resolve_fuel_index(i) /= 0) error stop 'undocumented NB code accepted'
  end do
  if (anderson%Resolve_fuel_index(204) /= 13) error stop 'Anderson crosswalk lost'
  if (anderson%Resolve_fuel_index(98) /= 14) error stop 'Anderson NB mapping lost'
  if (allocated(fuels%fgi_live)) error stop 'duplicate SB40 live table allocated'

  ! GR1 and GS1 distinguish herbaceous from woody data. Conversion uses exact
  ! short-ton/acre definitions rather than independently rounded metric tables.
  call Check(real(CONVERT_TON_PER_ACRE_TO_KG_PER_M_SQ),0.224170231238891,'load conversion')
  call Check(fuels%fgi_lh(10),0.50,'GS1 herb load')
  call Check(fuels%fgi_live_woody(10),0.65,'GS1 woody load')
  call Check(fuels%fuelheat(6),9000.0,'GR6 heat content')
  call Check(fuels%Cured_fraction(0.30),1.0,'full curing')
  call Check(fuels%Cured_fraction(0.75),0.5,'half curing')
  call Check(fuels%Cured_fraction(1.20),0.0,'uncured')
  do k = 1, 40
    do n = 0, 2
      mc = [0.06,0.07,0.08,0.08,0.30+0.45*n,0.90]
      loads = fuels%Component_loads(k,mc(5))
      total = real(sum(loads)*CONVERT_TON_PER_ACRE_TO_KG_PER_M_SQ)
      call Check(total,fuels%fgi(k),'curing preserves consumable dry inventory')
      call Check(fuels%Calc_effective_dead_load(k,mc(5)), &
          real(sum(loads(1:4))*CONVERT_TON_PER_ACRE_TO_KG_PER_M_SQ),'dead-load partition')
      call Calc_sb40_parameters(fuels,k,mc,beta,b,wind,r0,iboros,dead,live,mx)
      if (.not. all(ieee_is_finite([beta,b,wind,r0,iboros,dead,live,mx]))) error stop 'nonfinite component ROS'
      if (min(r0,iboros,dead,live) < 0.0) error stop 'negative reaction or ROS'
      if (scenario == 'reference') write(*,'(i4,1x,f5.2,4(1x,es20.12))') codes(k),mc(5),r0,dead,live,mx
    end do
  end do
  ! A shrub model with no herbaceous load isolates woody moisture sensitivity;
  ! the grass case isolates the retained live-herbaceous reaction during partial curing.
  mc = [0.03,0.04,0.05,0.05,1.20,0.60]
  call Calc_sb40_parameters(fuels,18,mc,beta,b,wind,r0,iboros,dead,live,mx)
  if (live <= 0.0) error stop 'woody reaction omitted'
  baseline = r0
  mc(6) = 3.0
  call Calc_sb40_parameters(fuels,18,mc,beta,b,wind,r0,iboros,dead,live,mx)
  if (r0 >= baseline) error stop 'woody moisture does not damp spread'
  mc = [0.01,0.01,0.01,0.01,0.75,0.90]
  call Calc_sb40_parameters(fuels,1,mc,beta,b,wind,r0,iboros,dead,live,mx)
  if (live <= 0.0) error stop 'remaining herbaceous reaction omitted'
  ! Saturated dead and live fuel extinguishes both components. No-fuel returns
  ! before any zero-load divisions, with zero reaction and base spread.
  mc = 10.0
  call Calc_sb40_parameters(fuels,10,mc,beta,b,wind,r0,iboros)
  if (r0 /= 0.0 .or. iboros /= 0.0) error stop 'reaction above extinction'
  call Calc_sb40_parameters(fuels,41,mc,beta,b,wind,r0,iboros)
  if (r0 /= 0.0 .or. iboros /= 0.0 .or. fuels%fgi(41) /= 0.0) error stop 'nonburnable reaction or inventory'

  ! Six SB40 classes retain the 1000h slot and independent live states. ROS
  ! must consume these class values instead of the deliberately wrong mean.
  call fmc%Init(fuels,0.08,0.75,0,47,0,3,0,1.0,0.90)
  if (size(fmc%fmc_gc,2) /= 6) error stop 'SB40 woody moisture class absent'
  mc = [0.06,0.07,0.08,0.08,0.75,0.90]
  do i = 1, 6
    fmc%fmc_gc(:,i,:) = mc(i)
  end do
  call fmc%Average_moisture_classes(0,47,0,3,1,46,1,2,indices,aggregate,fuels)
  loads = fuels%Moisture_loads(10,0.75)
  call Check(aggregate(10,1),sum(loads*[0.06,0.07,0.08,0.08,0.75,0.90])/sum(loads),'component moisture mean')
  ! Distinct nondefault prescribed moistures must reach ROS through Init. An
  ! unrelated aggregate exposes accidental use of a fallback or the mean. Check
  ! all fuel groups so both herbaceous and woody initialization affect results.
  call ros%Init(0,47,0,3,fuelmc_g_live=0.65,fuelmc_g_woody=1.10,fuelmc_g=0.05)
  aggregate = 9.0
  call ros%Set_params(0,47,0,3,1,46,1,2,fuels,indices,aggregate)
  mc = [0.05,0.05,0.05,0.05,0.65,1.10]
  do k = 1, 40
    call Calc_sb40_parameters(fuels,k,mc,beta,b,wind,r0,iboros)
    call Check(ros%r_0(k,1),r0,'ROS uses prescribed initialization moisture')
    call Check(ros%iboros(k,1),iboros,'reaction uses prescribed initialization moisture')
  end do
  ! Once class state is available, its values must supersede the prescribed
  ! controls, including distinct moisture for each dead size class.
  call ros%Set_params(0,47,0,3,1,46,1,2,fuels,indices,aggregate,fmc%fmc_gc)
  mc = [0.06,0.07,0.08,0.08,0.75,0.90]
  call Calc_sb40_parameters(fuels,10,mc,beta,b,wind,r0,iboros)
  call Check(ros%r_0(10,1),r0,'ROS uses component moisture')
  call Heat_check()
  print *, 'SB40 unit checks passed'
#ifdef DM_PARALLEL
  call MPI_Finalize(ierr)
#endif
contains
  subroutine Heat_check()
    ! Equal dry mass consumption isolates GR6's 9000 versus 8000 BTU/lb heat
    ! content. Varying moisture changes latent heat only; NB dry inventory is
    ! zero even if the numerical consumption fraction is nonzero.
    type(state_fire_t) :: grid
    real :: mass(3,1), sensible(3,1), latent(3,1)
    real(REAL64) :: fraction(3,1)
    allocate(fuel_scott_burgan_t::grid%fuels)
    call grid%fuels%Initialization(1.0)
    allocate(grid%fuel_index(3,1), grid%fmc_g(3,1))
    grid%fuel_index(:,1) = [1,6,41]
    grid%fmc_g(:,1) = [0.3,0.9,0.0]
    mass(:,1) = [1.0,1.0,0.0]
    fraction = 0.25_REAL64
    call Calc_fire_fluxes(4.0,grid,1,3,1,1,1,3,1,1,1,3,1,1,mass,fraction,sensible,latent)
    call Check(sensible(1,1),real(0.25_REAL64/4.0*8000.0*1055.0/0.45359237_REAL64),'dry-mass sensible heat')
    call Check(sensible(2,1)/sensible(1,1),1.125,'GR6 category heat')
    call Check(latent(2,1)/latent(1,1),1.46/0.86,'water per dry mass')
    if (sensible(3,1) /= 0.0 .or. latent(3,1) /= 0.0) error stop 'NB heat release'
  end subroutine

  subroutine Reference(code,moisture,spread,reaction_dead,reaction_live)
    integer, intent(in) :: code
    real, intent(in) :: moisture(6), spread, reaction_dead, reaction_live
    real :: beta_ref,b_ref,wind_ref,r0_ref,iboros_ref,dead_ref,live_ref
    call Calc_sb40_parameters(fuels,fuels%Resolve_fuel_index(code),moisture, &
        beta_ref,b_ref,wind_ref,r0_ref,iboros_ref,dead_ref,live_ref)
    call Check(r0_ref,spread,'Behave zero-wind spread')
    call Check(dead_ref,reaction_dead,'Behave dead reaction intensity')
    call Check(live_ref,reaction_live,'Behave live reaction intensity')
  end subroutine

  subroutine Check(actual,expected,description)
    real, intent(in) :: actual,expected
    character(len=*), intent(in) :: description
    if (abs(actual-expected) > 2.e-6*max(abs(expected),1.e-5)) then
      print *, description,actual,expected
      error stop 'SB40 numerical check failed'
    end if
  end subroutine
end program
